import numpy as np

def rotate_90_clockwise(m, iterations=1):
    for i in range(iterations):
        m = np.flip(m.transpose([1,0,2]), 1)
    return m

mat = np.array([
    [[1,1], [2,1], [3,1], [4,1], [5,1], [6,1], [7,1], [8,1]],
    [[9,2], [10,2], [11,2], [12,2], [13,2], [14,2], [15,2], [16,2]],
    [[17,3], [18,3], [19,3], [20,3], [21,3], [22,3], [23,3], [24,3]],
    [[25,4], [26,4], [27,4], [28,4], [29,4], [30,4], [31,4], [32,4]],
    [[33,5], [34,5], [35,5], [36,5], [37,5], [38,5], [39,5], [40,5]],
    [[41,6], [42,6], [43,6], [44,6], [45,6], [46,6], [47,6], [48,6]]
])

for i in range(5):
    m = rotate_90_clockwise(mat,i)
    print(f"\n{i}: {m}\n")
